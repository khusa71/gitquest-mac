/**
 * The player's real shell in a pty, with the GitQuest hooks from docs/CONTRACTS.md.
 * Output is cleaned of `ESC]777;gq;…BEL` sequences and batched (~16 ms) before it reaches the renderer.
 */
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawn, type IPty } from 'node-pty';
import { sandboxEnv, type GitQuestPaths } from '../realgit';
import { OscParser } from './osc';

export interface TerminalOptions {
  readonly paths: GitQuestPaths;
  /** Cleaned, batched output for the renderer. */
  send(data: string): void;
  /** A command line was submitted (preexec). */
  onCommandStart(command: string): void;
  /** The prompt is back (precmd). `command` is null when no command ran (empty Enter, first prompt). */
  onCommandDone(command: string | null, exitCode: number | null): void;
}

const HOOKS_ZSH = `autoload -Uz add-zsh-hook
_gq_preexec() { printf '\\e]777;gq;cmd;%s\\a' "$(printf '%s' "$1" | base64 | tr -d '\\n')"; }
_gq_precmd()  { local c=$?; printf '\\e]777;gq;done;%s\\a' "$c"; }
add-zsh-hook preexec _gq_preexec
add-zsh-hook precmd _gq_precmd
`;

// ponytail: bash hooks are best effort (DEBUG trap + history); a user DEBUG trap or HISTCONTROL=ignorespace can hide commands.
const HOOKS_BASH = `_gq_armed=
_gq_debug() {
  [ -n "$_gq_armed" ] || return
  case "$BASH_COMMAND" in _gq_precmd*) return ;; esac
  _gq_armed=
  local c; c=$(HISTTIMEFORMAT= builtin history 1 | sed 's/^ *[0-9]* *//')
  printf '\\e]777;gq;cmd;%s\\a' "$(printf '%s' "$c" | base64 | tr -d '\\n')"
}
_gq_precmd() { local c=$?; printf '\\e]777;gq;done;%s\\a' "$c"; _gq_armed=1; }
trap '_gq_debug' DEBUG
PROMPT_COMMAND="_gq_precmd\${PROMPT_COMMAND:+;$PROMPT_COMMAND}"
`;

const sq = (s: string) => `'${s.replace(/'/g, `'\\''`)}'`;

/**
 * Lines that re-apply what sandboxEnv changed, after the player's rc files ran
 * (so their rc can't silently point git back at ~/.gitconfig). PATH is left to their rc.
 */
function sandboxExports(sandbox: NodeJS.ProcessEnv, base: NodeJS.ProcessEnv): string {
  const lines: string[] = [];
  for (const [k, v] of Object.entries(sandbox)) {
    if (k !== 'PATH' && v !== undefined && base[k] !== v && /^[A-Za-z_]\w*$/.test(k)) lines.push(`export ${k}=${sq(v)}`);
  }
  for (const k of Object.keys(base)) if (!(k in sandbox) && /^GIT_\w*$/.test(k)) lines.push(`unset ${k}`);
  return lines.join('\n') + '\n';
}

/** Writes paths.shell/{.zshenv,.zprofile,.zshrc,.zlogin,.zlogout,bashrc}. Exported for tests. */
export function writeShellFiles(paths: GitQuestPaths, exportsBlock: string): void {
  mkdirSync(paths.shell, { recursive: true });
  const header = '# Generated by GitQuest on every launch. Edits are overwritten; put yours in your own rc files.\n';
  // .zshenv runs first: remember our dir, source the player's .zshenv with ZDOTDIR=$HOME,
  // and remember where their dotfiles live (their .zshenv may set ZDOTDIR).
  writeFileSync(
    path.join(paths.shell, '.zshenv'),
    `${header}_gq_dir="$ZDOTDIR"
ZDOTDIR="$HOME"
[[ -r "$HOME/.zshenv" ]] && source "$HOME/.zshenv"
_gq_user_dir="\${ZDOTDIR:-$HOME}"
ZDOTDIR="$_gq_dir"
`,
  );
  const passthrough = (name: string) =>
    `ZDOTDIR="\${_gq_user_dir:-$HOME}"
[[ -r "$ZDOTDIR/${name}" ]] && source "$ZDOTDIR/${name}"
ZDOTDIR="$_gq_dir"
`;
  for (const name of ['.zprofile', '.zlogin', '.zlogout']) writeFileSync(path.join(paths.shell, name), header + passthrough(name));
  // macOS /etc/zshrc ran with ZDOTDIR = ours; keep history in the player's usual file.
  const history = '[[ $HISTFILE == "$_gq_dir/.zsh_history" ]] && HISTFILE="${_gq_user_dir:-$HOME}/.zsh_history"\n';
  writeFileSync(path.join(paths.shell, '.zshrc'), header + history + passthrough('.zshrc') + exportsBlock + HOOKS_ZSH);
  writeFileSync(
    path.join(paths.shell, 'bashrc'),
    `${header}[ -r /etc/profile ] && . /etc/profile
if [ -r ~/.bash_profile ]; then . ~/.bash_profile
elif [ -r ~/.bash_login ]; then . ~/.bash_login
elif [ -r ~/.profile ]; then . ~/.profile
elif [ -r ~/.bashrc ]; then . ~/.bashrc
fi
${exportsBlock}${HOOKS_BASH}`,
  );
}

/** Shell, argv and env for the pty. Exported for tests. */
export function shellLaunch(paths: GitQuestPaths, base: NodeJS.ProcessEnv = process.env) {
  const shell = base.SHELL || '/bin/zsh';
  const sandbox = sandboxEnv(paths, base);
  writeShellFiles(paths, sandboxExports(sandbox, base));
  const name = path.basename(shell);
  const args = name === 'bash' ? ['--rcfile', path.join(paths.shell, 'bashrc'), '-i'] : ['-i', '-l']; // other shells: no hooks, the watcher still sees changes
  const env: Record<string, string> = {};
  for (const [k, v] of Object.entries(sandbox)) if (v !== undefined) env[k] = v;
  Object.assign(env, { ZDOTDIR: paths.shell, TERM: 'xterm-256color', COLORTERM: 'truecolor', LANG: env.LANG || 'en_US.UTF-8' });
  delete env.ELECTRON_RENDERER_URL;
  return { shell, args, env };
}

export class Terminal {
  private pty: IPty | null = null;
  private parser = new OscParser();
  private command: string | null = null;
  private out = '';
  private flushTimer: NodeJS.Timeout | null = null;
  private cols = 80;
  private rows = 24;
  private spawnedAt = 0;
  private quitting = false;
  /** Directory the current shell was started in (null when not running). */
  cwd: string | null = null;

  constructor(private readonly opts: TerminalOptions) {}

  /** Starts the shell if it isn't running. cwd = the repo, or home until setup has created it. */
  start(): void {
    if (this.pty || this.quitting) return;
    const { paths } = this.opts;
    const cwd = existsSync(paths.repo) ? paths.repo : os.homedir();
    let launch: ReturnType<typeof shellLaunch>;
    let p: IPty;
    try {
      launch = shellLaunch(paths);
      p = spawn(launch.shell, launch.args, { name: 'xterm-256color', cols: this.cols, rows: this.rows, cwd, env: launch.env });
    } catch (e) {
      console.error('[gitquest] terminal spawn failed', e);
      this.emit(`\r\n\x1b[31mGitQuest could not start your shell: ${String(e)}\x1b[0m\r\n`);
      return;
    }
    this.pty = p;
    this.cwd = cwd;
    this.parser = new OscParser();
    this.command = null;
    this.spawnedAt = Date.now();
    p.onData((chunk) => this.onData(chunk));
    p.onExit(({ exitCode }) => {
      if (this.pty !== p) return; // replaced on purpose
      this.pty = null;
      this.cwd = null;
      if (this.quitting) return;
      if (Date.now() - this.spawnedAt < 2000) {
        this.emit(`\r\n\x1b[31m[shell exited right away (code ${exitCode}); not restarting — check your shell rc files]\x1b[0m\r\n`);
        return;
      }
      this.emit('\r\n\x1b[2m[shell exited — starting a new one]\x1b[0m\r\n');
      this.start();
    });
  }

  write(data: string): void {
    this.pty?.write(data);
  }

  /** The first resize (sent once xterm is mounted and listening) starts the shell at the right size. */
  resize(cols: number, rows: number): void {
    this.cols = cols;
    this.rows = rows;
    if (!this.pty) this.start();
    else this.pty.resize(cols, rows);
  }

  /** Restarts the shell (e.g. in the repo once setup has created it). */
  respawn(): void {
    const old = this.pty;
    if (!old) return;
    this.pty = null;
    old.kill();
    this.emit('\x1b[H\x1b[2J');
    this.start();
  }

  kill(): void {
    this.quitting = true;
    const p = this.pty;
    this.pty = null;
    p?.kill();
  }

  private onData(chunk: string): void {
    const { output, events } = this.parser.feed(chunk);
    if (output) this.emit(output);
    for (const ev of events) {
      if (ev.kind === 'cmd') {
        this.command = ev.command;
        this.opts.onCommandStart(ev.command);
      } else {
        const command = this.command;
        this.command = null;
        this.opts.onCommandDone(command, ev.exitCode);
      }
    }
  }

  private emit(data: string): void {
    this.out += data;
    this.flushTimer ??= setTimeout(() => {
      this.flushTimer = null;
      const data = this.out;
      this.out = '';
      this.opts.send(data);
    }, 16);
  }
}
